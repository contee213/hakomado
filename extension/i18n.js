/** スクリプト用の文言。{0} {1} … に引数を入れる */
function tr(key, ...args) {
  const m = MESSAGES[key];
  const s = m ? m[LANG === 'ja' ? 0 : 1] : key;
  return s.replace(/\{(\d+)\}/g, (_, n) => String(args[Number(n)] ?? ''));
}

